const text = '제5조(출장비 집행 및 관리) ① 사업 수행을 위하여 출장할 수 있으며, 출장비는 출장여비 항목으로 집행한다. ② 출장비 집행 시 사전 출장신청 및 사후 출장복명을 원칙으로 한다.';
let formatted = text
  .replace(/(①|②|③|④|⑤|⑥|⑦|⑧|⑨|⑩|⑪|⑫|⑬|⑭|⑮)/g, '\n$1')
  .replace(/(?<!\d+\.\s*)(?<!\d)(\d{1,2}\.)\s+(?=[^\d])/g, '\n$1 ')
  .replace(/(^|\s)([가-하]\.)\s+/g, '$1\n$2 ')
  .replace(/(제\d+조의?\d*\s*[\[〔(（][^\]〕)）]+[\]〕)）])\s*\n([①-⑮])/g, '$1 $2')
  .replace(/(제\d+조의?\d*\s*[\[〔(（][^\]〕)）]+[\]〕)）])/g, '\n\n$1')
  .replace(/(제\d+(?:장|절|관)\s+[^\s]+)/g, '\n\n$1')
  .replace(/(^|\n)(부\s*칙)\s*(.*)/g, '\n\n$2 $3');
console.log(formatted.split('\n').map(l => l.trim()).filter(l => l));
