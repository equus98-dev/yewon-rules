  content TEXT NOT NULL, 
  author TEXT NOT NULL, 
  password TEXT NOT NULL, 
  attachmentUrl TEXT, 
  attachmentName TEXT, 
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, 
